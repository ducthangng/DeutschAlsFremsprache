type Server struct {
	cfg        config.Config
	store      *store.Store
	auth       *auth.Auth
	speech     *speech.Client
	translator translate.Translator
	openai     *openai.Client
	media      storage.Storage
	ttsFlight  singleflight.Group // one synthesis per clip even under concurrent requests
}

const mediaPath = "/api/media/"

func New(ctx context.Context, cfg config.Config, st *store.Store) (*Server, error) {
	var tr translate.Translator = &translate.MyMemory{Email: cfg.MyMemoryEmail}
	if cfg.TranslatorKey != "" {
		tr = &translate.Azure{Key: cfg.TranslatorKey, Region: cfg.TranslatorRegion, USDPerMillionChars: cfg.TranslatorUSDPerMillion}
	}
	var media storage.Storage = &storage.Local{Dir: filepath.Join(cfg.DataDir, "media"), BaseURL: mediaPath, PublicURL: cfg.PublicURL, Secret: []byte(cfg.JWTSecret)}
	if cfg.S3Bucket != "" {
		s3, err := storage.NewS3(ctx, storage.S3Config{Bucket: cfg.S3Bucket, Region: cfg.S3Region, Prefix: cfg.S3Prefix,
			Endpoint: cfg.S3Endpoint, AccessKey: cfg.AWSAccessKey, SecretKey: cfg.AWSSecretKey})
		if err != nil {
			return nil, fmt.Errorf("s3: %w", err)
		}
		media = s3
	}
	oa := openai.New(openai.Config{APIKey: cfg.OpenAIKey, BaseURL: cfg.OpenAIBaseURL,
		ChatModel: cfg.OpenAIChatModel, ChatUSDPerMInput: cfg.OpenAIChatUSDPerMIn, ChatUSDPerMOutput: cfg.OpenAIChatUSDPerMOut,
		TTSModel: cfg.OpenAITTSModel, TTSUSDPerMinute: cfg.OpenAITTSUSDPerMinute, TTSUSDPerMillionChars: cfg.OpenAITTSUSDPerMChars})
	return &Server{cfg: cfg, store: st, auth: auth.New(cfg.JWTSecret), speech: speech.New(cfg.AzureKey, cfg.AzureRegion),
		translator: tr, openai: oa, media: media}, nil
}

// ttsEnabled reports whether reference speech for a language is generated by
// OpenAI (all supported languages); otherwise the browser speaks.
func (s *Server) ttsEnabled(language string) bool {
	return s.openai.Enabled() && topic.Languages[language]
}

func (s *Server) recordingsDir() string { return filepath.Join(s.cfg.DataDir, "recordings") }

