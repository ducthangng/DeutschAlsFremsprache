-- A topic's word list used to live in its owner's Vocabulary Pocket, so every
-- AI-generated topic filled the pocket with words nobody chose. The list now
-- belongs to the topic; the pocket only holds words a learner adds by hand.
CREATE TABLE topic_vocab (
    id        BIGSERIAL PRIMARY KEY,
    topic_id  BIGINT  NOT NULL REFERENCES topics (id) ON DELETE CASCADE,
    position  INTEGER NOT NULL,
    term      TEXT    NOT NULL CHECK (term <> ''),
    meaning   TEXT    NOT NULL DEFAULT '',
    example   TEXT    NOT NULL DEFAULT '',
    image_key TEXT    NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX topic_vocab_topic_term_idx ON topic_vocab (topic_id, lower(term));

-- Keep the word lists of existing topics before the pockets are emptied.
INSERT INTO topic_vocab (topic_id, position, term, meaning, example, image_key)
SELECT v.topic_id, row_number() OVER (PARTITION BY v.topic_id ORDER BY v.created_at, v.id) - 1,
       v.term, v.meaning, v.example, v.image_key
FROM vocab_entries v
JOIN topics t ON t.id = v.topic_id AND t.user_id = v.user_id
ON CONFLICT DO NOTHING;

-- Start every Vocabulary Pocket from scratch.
TRUNCATE vocab_reviews, vocab_entries RESTART IDENTITY;

-- Grammar exercise sets generated by OpenAI: multiple choice, rearranging,
-- reading, listening (Azure TTS audio, cached in tts_audio / S3) and
-- English → German translation.
CREATE TABLE grammar_sets (
    id               BIGSERIAL PRIMARY KEY,
    user_id          BIGINT           NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    grammar          TEXT             NOT NULL,              -- the grammar point asked for
    level            TEXT             NOT NULL,
    model            TEXT             NOT NULL,
    sections         JSONB            NOT NULL,              -- requested question counts per section
    status           TEXT             NOT NULL DEFAULT 'generating' CHECK (status IN ('generating', 'ready', 'failed')),
    error            TEXT             NOT NULL DEFAULT '',
    content          JSONB,                                  -- the generated exercises
    audio_key        TEXT             NOT NULL DEFAULT '',   -- listening audio in media storage
    answers          JSONB,                                  -- the learner's latest answers
    writing_feedback JSONB,                                  -- AI grading of the translations
    cost_usd         DOUBLE PRECISION NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ      NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX grammar_sets_user_idx ON grammar_sets (user_id, created_at DESC);

ALTER TABLE ai_usage DROP CONSTRAINT ai_usage_kind_check;
ALTER TABLE ai_usage ADD CONSTRAINT ai_usage_kind_check CHECK (kind IN ('script', 'tts', 'image', 'simulation', 'grammar'));
ALTER TABLE ai_usage ADD COLUMN grammar_set_id BIGINT REFERENCES grammar_sets (id) ON DELETE SET NULL;
CREATE INDEX ai_usage_grammar_idx ON ai_usage (grammar_set_id);
